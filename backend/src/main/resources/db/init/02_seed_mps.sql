INSERT INTO mps (name, state_id, state_name, mp_type, term_start_year, term_end_year, allocated_amount_paise)
SELECT
    REGEXP_REPLACE(s.mp_name, '\s*\(\d{4}-\d{2,4}\).*$', '') AS name,
    st.id AS state_id,
    s.state_name,
    CASE
        WHEN s.mp_type = 'Nominated MP' THEN 'NOMINATED'
        ELSE 'ELECTED'
    END AS mp_type,
    CAST(SUBSTRING(s.mp_name FROM '\((\d{4})-\d{2,4}\)') AS INTEGER) AS term_start_year,
    CASE
        WHEN LENGTH(SUBSTRING(s.mp_name FROM '\d{4}-(\d{2,4})\)')) = 2
        THEN 2000 + CAST(SUBSTRING(s.mp_name FROM '\d{4}-(\d{2})\)') AS INTEGER)
        ELSE CAST(SUBSTRING(s.mp_name FROM '\d{4}-(\d{4})\)') AS INTEGER)
    END AS term_end_year,
    CAST(s.allocated_amount * 100 AS BIGINT) AS allocated_amount_paise
FROM mp_staging s
JOIN states st ON LOWER(TRIM(st.name)) = LOWER(TRIM(s.state_name))
ON CONFLICT DO NOTHING;

